#!/usr/bin/env python3
"""Generate the initial contents of the text-mode character RAM.

Usage:  python gen_screen.py <out.hex>

The screen is 80 columns x 30 rows. Each cell is one 16-bit word:
    bits  7..0  character code (CP437, see bdf2hex.py)
    bits 11..8  foreground color (0..15, CGA palette)
    bits 15..12 background color (0..15)
    address = row * 80 + col
The RAM has 4096 words; only the first 2400 are visible.
"""

import sys

COLS, ROWS, DEPTH = 80, 30, 4096

# CGA palette indices
BLACK, BLUE, GREEN, CYAN, RED, MAGENTA, BROWN, LGRAY = range(8)
DGRAY, LBLUE, LGREEN, LCYAN, LRED, LMAGENTA, YELLOW, WHITE = range(8, 16)
NAMES = ["black", "blue", "green", "cyan", "red", "magenta", "brown", "light gray",
         "dark gray", "light blue", "light green", "light cyan", "light red",
         "light magenta", "yellow", "white"]

# Row/column of the hex frame counter that the hardware writes each frame.
# Must match FRAME_ROW / FRAME_COL in 03_text/top.v.
FRAME_ROW, FRAME_COL = 26, 30

screen = [(BLACK << 12) | (LGRAY << 8) | 0x20] * DEPTH   # blank: space, gray on black


def put(row, col, code, fg=LGRAY, bg=BLACK):
    screen[row * COLS + col] = (bg << 12) | (fg << 8) | (code & 0xFF)


# CP437 symbols at codes 0x01-0x1F (Python's cp437 codec maps those to
# control characters, so look them up here). Same table as in bdf2hex.py.
CP437_LOW = {u: code for code, u in enumerate([
    None,   0x263A, 0x263B, 0x2665, 0x2666, 0x2663, 0x2660, 0x2022,
    0x25D8, 0x25CB, 0x25D9, 0x2642, 0x2640, 0x266A, 0x266B, 0x263C,
    0x25BA, 0x25C4, 0x2195, 0x203C, 0x00B6, 0x00A7, 0x25AC, 0x21A8,
    0x2191, 0x2193, 0x2192, 0x2190, 0x221F, 0x2194, 0x25B2, 0x25BC,
]) if u is not None}


def to_cp437(ch):
    if ord(ch) in CP437_LOW:
        return CP437_LOW[ord(ch)]
    return ch.encode("cp437")[0]


def text(row, col, s, fg=LGRAY, bg=BLACK):
    for i, ch in enumerate(s):
        put(row, col + i, to_cp437(ch), fg, bg)


def box(top, left, bottom, right, fg=LCYAN, bg=BLACK):
    """Double-line box using the CP437 box-drawing characters."""
    put(top, left, 0xC9, fg, bg)
    put(top, right, 0xBB, fg, bg)
    put(bottom, left, 0xC8, fg, bg)
    put(bottom, right, 0xBC, fg, bg)
    for c in range(left + 1, right):
        put(top, c, 0xCD, fg, bg)
        put(bottom, c, 0xCD, fg, bg)
    for r in range(top + 1, bottom):
        put(r, left, 0xBA, fg, bg)
        put(r, right, 0xBA, fg, bg)


# Title bar across the full width
for c in range(COLS):
    put(0, c, 0x20, WHITE, BLUE)
text(0, 2, "Tang Nano 9K  -  80x30 text mode  -  640x480 @ 60 Hz", WHITE, BLUE)

# Full character set, 16 x 16, inside a box
text(2, 2, "Character set (CP437)", YELLOW)
box(3, 1, 20, 35)
for code in range(256):
    r, c = divmod(code, 16)
    put(4 + r, 3 + c * 2, code, WHITE)

# The 16 palette colors as background, with the name on top
text(2, 40, "Palette", YELLOW)
for i in range(16):
    fg = BLACK if i in (LGRAY, LGREEN, LCYAN, YELLOW, WHITE, GREEN, CYAN) else WHITE
    label = f" {i:2d} {NAMES[i]:<14}"
    text(4 + i, 40, label, fg, i)
    text(4 + i, 40 + len(label) + 1, "Text", i)    # same color as foreground

# Some sample text
text(22, 2, "Hello from the FPGA! Every character on this screen comes from a", LGRAY)
text(23, 2, "4096 x 16-bit character RAM and a 4 KB font ROM, both in block RAM.", LGRAY)
text(24, 2, "░▒▓█ shading   ←↑→↓ arrows   "
            "☺♥♦♣♠ symbols   àèéìòù", LGREEN)

text(FRAME_ROW, 2, "Frame counter (hardware):", LGRAY)
text(FRAME_ROW, FRAME_COL, "--------", YELLOW)

text(29, 2, "S1 = reset", DGRAY)


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    with open(sys.argv[1], "w", newline="\n") as f:
        f.write("// Character RAM init generated by tools/gen_screen.py - do not edit by hand\n")
        for addr, word in enumerate(screen):
            if addr % COLS == 0 and addr < COLS * ROWS:
                f.write(f"// row {addr // COLS}\n")
            elif addr == COLS * ROWS:
                f.write("// not visible\n")
            f.write(f"{word:04X}\n")
    print(f"wrote {sys.argv[1]}: {DEPTH} words")


if __name__ == "__main__":
    main()

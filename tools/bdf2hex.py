#!/usr/bin/env python3
"""Convert an 8x16 BDF bitmap font into a font ROM image for $readmemh.

Usage:  python bdf2hex.py <font.bdf> <out.hex>

Output layout: 256 characters x 16 rows = 4096 lines, one byte per line.
    address = char_code * 16 + row      (row 0 = top of the cell)
    bit 7   = leftmost pixel, bit 0 = rightmost pixel

Character codes follow IBM code page 437 (the original PC character set), so
besides ASCII we get the PC box-drawing, block and symbol characters:
    0x01-0x1F : smileys, card suits, arrows ...   (CP437 graphics)
    0x20-0x7E : ASCII
    0x7F      : house symbol
    0x80-0xFF : accented letters, box drawing, blocks, Greek, math
Codes whose glyph is missing from the font are left blank.
"""

import sys

# CP437 0x00-0x1F and 0x7F are control codes in Python's cp437 codec, but on
# the PC screen they were these symbols.
CP437_LOW = [
    None,   0x263A, 0x263B, 0x2665, 0x2666, 0x2663, 0x2660, 0x2022,
    0x25D8, 0x25CB, 0x25D9, 0x2642, 0x2640, 0x266A, 0x266B, 0x263C,
    0x25BA, 0x25C4, 0x2195, 0x203C, 0x00B6, 0x00A7, 0x25AC, 0x21A8,
    0x2191, 0x2193, 0x2192, 0x2190, 0x221F, 0x2194, 0x25B2, 0x25BC,
]

CELL_W, CELL_H = 8, 16


def cp437_to_unicode(code):
    if code < 0x20:
        return CP437_LOW[code]
    if code == 0x7F:
        return 0x2302
    return ord(bytes([code]).decode("cp437"))


def parse_bdf(path):
    """Return (ascent, {unicode: (bbx, [row ints])})."""
    glyphs = {}
    ascent = None
    with open(path, encoding="latin-1") as f:
        lines = iter(f.read().splitlines())
    for line in lines:
        if line.startswith("FONT_ASCENT"):
            ascent = int(line.split()[1])
        elif line.startswith("STARTCHAR"):
            enc, bbx, rows = None, None, []
            for line in lines:
                if line.startswith("ENCODING"):
                    enc = int(line.split()[1])
                elif line.startswith("BBX"):
                    bbx = tuple(int(v) for v in line.split()[1:5])
                elif line.startswith("BITMAP"):
                    for line in lines:
                        if line.startswith("ENDCHAR"):
                            break
                        rows.append(int(line, 16))
                    break
            if enc is not None and bbx is not None:
                glyphs[enc] = (bbx, rows)
    if ascent is None:
        sys.exit("BDF has no FONT_ASCENT property")
    return ascent, glyphs


def render_cell(ascent, bbx, rows):
    """Place a glyph bitmap into an 8x16 cell, using the font baseline."""
    w, h, xoff, yoff = bbx
    cell = [0] * CELL_H
    nbytes = (w + 7) // 8
    top = ascent - (yoff + h)           # cell row of the glyph's first bitmap row
    for i, bits in enumerate(rows):
        r = top + i
        if not 0 <= r < CELL_H:
            continue
        # BDF rows are left-aligned in whole bytes; keep the leftmost w pixels
        value = bits >> (nbytes * 8 - w)
        shift = CELL_W - w - xoff
        value = value << shift if shift >= 0 else value >> -shift
        cell[r] = value & 0xFF
    return cell


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    ascent, glyphs = parse_bdf(sys.argv[1])

    out, missing = [], []
    for code in range(256):
        u = cp437_to_unicode(code)
        if u is not None and u in glyphs:
            cell = render_cell(ascent, *glyphs[u])
        else:
            cell = [0] * CELL_H
            if code not in (0x00, 0x20, 0xFF):      # these are blank on purpose
                missing.append(code)
        # Comment line per glyph; ASCII only, to keep every tool's hex parser happy
        if u is None:
            label = ""
        elif 0x21 <= u <= 0x7E:
            label = f"'{chr(u)}'"
        else:
            label = f"U+{u:04X}"
        out.append(f"// 0x{code:02X} {label}".rstrip())
        out.extend(f"{b:02X}" for b in cell)

    with open(sys.argv[2], "w", encoding="utf-8", newline="\n") as f:
        f.write("// Font ROM generated by tools/bdf2hex.py - do not edit by hand\n")
        f.write("// Spleen 8x16, Copyright (c) 2018-2026 Frederic Cambus, BSD 2-Clause\n")
        f.write("// (see tools/font/LICENSE-spleen)\n")
        f.write("\n".join(out) + "\n")

    print(f"wrote {sys.argv[2]}: 256 glyphs, {len(missing)} missing:",
          " ".join(f"{c:02X}" for c in missing) or "none")


if __name__ == "__main__":
    main()
